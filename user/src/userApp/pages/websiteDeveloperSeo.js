export function buildWebsiteDeveloperStaticHtml(baseDistHtml) {
  let html = baseDistHtml;

  const replaceTag = (pattern, replacement) => {
    html = html.replace(pattern, () => replacement);
  };

  replaceTag(
    /<title>[\s\S]*?<\/title>/i,
    `<title data-rh="true">${escapeHtml(SEO_META.title)}</title>`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']description["'][^>]*>/i,
    `<meta name="description" content="${escapeHtml(SEO_META.description)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']keywords["'][^>]*>/i,
    `<meta name="keywords" content="${escapeHtml(SEO_META.keywords)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']author["'][^>]*>/i,
    `<meta name="author" content="${escapeHtml(`${DEV_NAME} (${DEV_BRAND})`)}" data-rh="true" />`,
  );

  replaceTag(
    /<link\b[^>]*\brel=["']canonical["'][^>]*>/i,
    `<link rel="canonical" href="${escapeHtml(CANONICAL)}" data-rh="true" />\n    <link rel="alternate" hreflang="en-IN" href="${escapeHtml(CANONICAL)}" data-rh="true" />\n    <link rel="alternate" hreflang="x-default" href="${escapeHtml(CANONICAL)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']geo\.placename["'][^>]*>/i,
    `<meta name="geo.placename" content="${escapeHtml(DEV_LOCATION)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bproperty=["']og:type["'][^>]*>/i,
    `<meta property="og:type" content="profile" data-rh="true" />\n    <meta property="profile:first_name" content="Ravi" data-rh="true" />\n    <meta property="profile:last_name" content="Sharma" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bproperty=["']og:title["'][^>]*>/i,
    `<meta property="og:title" content="${escapeHtml(SEO_META.ogTitle)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bproperty=["']og:description["'][^>]*>/i,
    `<meta property="og:description" content="${escapeHtml(SEO_META.ogDescription)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bproperty=["']og:url["'][^>]*>/i,
    `<meta property="og:url" content="${escapeHtml(CANONICAL)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bproperty=["']og:image:alt["'][^>]*>/i,
    `<meta property="og:image:alt" content="${escapeHtml(SEO_META.imageAlt)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']twitter:title["'][^>]*>/i,
    `<meta name="twitter:title" content="${escapeHtml(SEO_META.twitterTitle)}" data-rh="true" />`,
  );

  replaceTag(
    /<meta\b[^>]*\bname=["']twitter:description["'][^>]*>/i,
    `<meta name="twitter:description" content="${escapeHtml(SEO_META.twitterDescription)}" data-rh="true" />`,
  );

  replaceTag(
    /<script\b[^>]*type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>/i,
    `<script type="application/ld+json" data-rh="true">${WEBSITE_DEVELOPER_JSONLD}</script>`,
  );

  replaceTag(
    /<body\b[^>]*itemscope[^>]*>/i,
    "<body>",
  );

  replaceTag(
    /<!-- Semantic metadata for no-script crawlers -->[\s\S]*?<noscript>[\s\S]*?<\/noscript>/i,
    "<!-- Pre-rendered semantic content in #root for website-developer -->",
  );

  replaceTag(
    /<div\s+id=["']root["']>\s*<\/div>/i,
    `<div id="root">${renderStaticDeveloperRootHtml()}</div>`,
  );

  return html;
}
